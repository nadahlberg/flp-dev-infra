"""Seed the flp-dev CourtListener: users, the MCP OAuth app, sample data.

Run by bootstrap.sh inside the CL image with DJANGO_SETTINGS_MODULE set.
Idempotent: users and the application are updated in place, sample data is
only generated when the database has no dockets yet.
"""

import os

import django

django.setup()

from cl.search.models import Docket
from cl.users.models import UserProfile
from django.contrib.auth.models import User
from django.core.management import call_command
from oauth2_provider.models import get_application_model


def ensure_user(
    username: str, email: str, password: str, *, superuser: bool = False
) -> User:
    """Create or update a user with a confirmed email address."""
    user, _ = User.objects.get_or_create(username=username, defaults={"email": email})
    user.email = email
    user.set_password(password)
    user.is_active = True
    user.is_staff = superuser
    user.is_superuser = superuser
    user.save()
    profile, _ = UserProfile.objects.get_or_create(user=user)
    profile.email_confirmed = True
    profile.save()
    return user


def ensure_mcp_application(owner: User) -> None:
    """Register the MCP server as a confidential OAuth client of this CL.

    The id and secret are generated by Pulumi and handed to the MCP server as
    COURTLISTENER_OAUTH_CLIENT_ID / _SECRET; its callback is
    <MCP_BASE_URL>/auth/callback.
    """
    Application = get_application_model()
    Application.objects.update_or_create(
        client_id=os.environ["MCP_OAUTH_CLIENT_ID"],
        defaults={
            "user": owner,
            "name": "flp-dev MCP server",
            "client_type": Application.CLIENT_CONFIDENTIAL,
            "authorization_grant_type": Application.GRANT_AUTHORIZATION_CODE,
            "redirect_uris": f"{os.environ['MCP_BASE_URL'].rstrip('/')}/auth/callback",
            "client_secret": os.environ["MCP_OAUTH_CLIENT_SECRET"],
            "algorithm": Application.RS256_ALGORITHM,
            "skip_authorization": False,
        },
    )


def main() -> None:
    password = os.environ["DEV_USER_PASSWORD"]
    admin = ensure_user(
        os.environ.get("DEV_USER_NAME", "dev"),
        os.environ["DEV_USER_EMAIL"],
        password,
        superuser=True,
    )
    for n in range(1, int(os.environ.get("TEST_USER_COUNT", "3")) + 1):
        ensure_user(f"test{n}", f"test{n}@example.com", password)

    ensure_mcp_application(admin)

    if os.environ.get("SEED_DEV_DATA", "on") == "on" and not Docket.objects.exists():
        call_command("make_dev_data")


if __name__ == "__main__":
    main()
